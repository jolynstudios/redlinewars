#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const AllowedArgs = new Set(['--print', '--write-generated']);
if (args.some(arg => !AllowedArgs.has(arg)) || new Set(args).size !== args.length)
{
	console.error('usage: node strategy-catalog-gate.mjs [--print] [--write-generated]');
	process.exit(2);
}

const PrintMenu = args.includes('--print');
const WriteGenerated = args.includes('--write-generated');
const TestDirectory = path.dirname(fileURLToPath(import.meta.url));
const StrategyDirectory = path.resolve(TestDirectory, '../agent-sidecar/knowledge/strategies');
const CatalogPath = path.join(StrategyDirectory, 'catalog.json');
const ManualPath = path.join(StrategyDirectory, 'situation-manual.json');
const GeneratedCatalogPath = path.resolve(TestDirectory, '../AgentMode/AgentStrategyCatalog.Generated.cs');
const errors = [];

const AllowedFactions = new Set(['allies', 'both', 'soviets']);
const AllowedArchetypes = new Set(['air', 'boom', 'naval', 'pressure', 'rush', 'sabotage', 'turtle-tech']);
const AllowedRequirements = new Set(['enemyShoreReachable', 'landRoute', 'sharedWater', 'wideMap']);
const AllowedActionTypes = new Set([
	'assignGroup',
	'attackMove',
	'capture',
	'controlBuildPlan',
	'controlMission',
	'guard',
	'placeBuildingAuto',
	'queueBuildPlan',
	'queueMission',
	'repair',
	'sell',
	'setPolicy',
	'spyPlane',
	'startProduction'
]);
const AllowedEpistemics = new Set(['curatedHeuristic', 'derivedComparison', 'ruleFact']);
const IdPattern = /^[a-z0-9][a-z0-9-]{0,31}$/;
const ClaimIdPattern = /^[A-Z]{2}[0-9]+$/;
const TagPattern = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;
const HashPattern = /^[0-9a-f]{64}$/;

function fail(message)
{
	errors.push(message);
}

function readJson(file, label)
{
	try
	{
		return JSON.parse(fs.readFileSync(file, 'utf8'));
	}
	catch (error)
	{
		fail(`${label}: ${error.message}`);
		return null;
	}
}

function canonicalJson(value)
{
	if (Array.isArray(value))
		return `[${value.map(canonicalJson).join(',')}]`;

	if (value && typeof value === 'object')
		return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`;

	return JSON.stringify(value);
}

function sha256(value)
{
	return crypto.createHash('sha256').update(value).digest('hex');
}

function isObject(value)
{
	return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function csharpString(value)
{
	return JSON.stringify(value);
}

