function exactKeys(value, expected, label)
{
	if (!isObject(value))
	{
		fail(`${label} must be an object`);
		return false;
	}

	const actual = Object.keys(value).sort();
	const wanted = [...expected].sort();
	if (actual.join('\0') !== wanted.join('\0'))
		fail(`${label} keys must be exactly ${wanted.join(', ')} (got ${actual.join(', ')})`);

	return true;
}

function boundedString(value, min, max, label)
{
	if (typeof value !== 'string' || value.length < min || value.length > max)
		fail(`${label} must be a string of ${min}..${max} characters`);
}

function boundedArray(value, min, max, label)
{
	if (!Array.isArray(value) || value.length < min || value.length > max)
	{
		fail(`${label} must contain ${min}..${max} items`);
		return [];
	}

	return value;
}

function uniqueStrings(value, min, max, label, pattern = null)
{
	const items = boundedArray(value, min, max, label);
	const seen = new Set();
	for (const item of items)
	{
		if (typeof item !== 'string' || item.length === 0 || (pattern && !pattern.test(item)))
			fail(`${label} contains an invalid string: ${JSON.stringify(item)}`);
		else if (seen.has(item))
			fail(`${label} contains duplicate ${JSON.stringify(item)}`);
		else
			seen.add(item);
	}

	return items;
}

function graphIdentifiers(graph)
{
	const actors = new Set();
	const weapons = new Set();
	const weaponActors = new Map();
	if (!isObject(graph) || !Array.isArray(graph.actors))
	{
		fail('rules graph must contain an actors array');
		return { actors, weapons, weaponActors };
	}

	for (const actor of graph.actors)
	{
		if (typeof actor?.id === 'string')
			actors.add(actor.id);

		for (const armament of actor?.armaments ?? [])
			if (typeof armament?.weaponId === 'string')
			{
				weapons.add(armament.weaponId);
				if (!weaponActors.has(armament.weaponId))
					weaponActors.set(armament.weaponId, new Set());
				weaponActors.get(armament.weaponId).add(actor.id);
			}
	}

	return { actors, weapons, weaponActors };
}

function validateCard(card, entry, catalogIds, graphIds)
{
	const label = `card ${entry.id}`;

	// Optional rich-playbook sections (era3.1): validated then removed from a
	// shallow copy so the strict key check below still rejects true strangers.
	const cardCore = { ...card };
	for (const key of ['opening', 'composition', 'execution']) {
		if (cardCore[key] == null)
			continue;
		for (const [index, text] of boundedArray(cardCore[key], 1, 16, `${label}.${key}`).entries())
			boundedString(text, 1, 200, `${label}.${key}[${index}]`);
		delete cardCore[key];
	}

	if (cardCore.targets != null) {
		const allowed = new Set(['harvesters', 'refineries', 'missionDriven']);
		for (const key of Object.keys(cardCore.targets)) {
			if (!allowed.has(key))
				fail(`${label}.targets has unknown key ${key}`);
		}

		for (const key of ['harvesters', 'refineries'])
			if (cardCore.targets[key] != null &&
				(!Number.isInteger(cardCore.targets[key]) || cardCore.targets[key] < 1 || cardCore.targets[key] > 16))
				fail(`${label}.targets.${key} must be an integer between 1 and 16`);
		if (cardCore.targets.missionDriven != null && typeof cardCore.targets.missionDriven !== 'boolean')
			fail(`${label}.targets.missionDriven must be a boolean`);
		delete cardCore.targets;
	}

	exactKeys(cardCore, [
		'abortTransitions', 'archetype', 'avoidWhen', 'claims', 'effectiveAgainst', 'faction', 'hardCounteredBy',
		'id', 'openingSummary', 'phases', 'requirements', 'retrieval', 'schemaVersion', 'title', 'version', 'when'
	], label);

	if (card.schemaVersion !== 1)
		fail(`${label}.schemaVersion must be 1`);
	if (!IdPattern.test(card.id ?? ''))
		fail(`${label}.id is invalid`);
	if (!Number.isInteger(card.version) || card.version < 1)
		fail(`${label}.version must be a positive integer`);
	boundedString(card.title, 1, 80, `${label}.title`);
	boundedString(card.openingSummary, 1, 160, `${label}.openingSummary`);
	if (!AllowedFactions.has(card.faction))
		fail(`${label}.faction is invalid`);
	if (!AllowedArchetypes.has(card.archetype))
		fail(`${label}.archetype is invalid`);

	for (const key of ['id', 'version', 'title', 'faction', 'archetype', 'openingSummary'])
		if (entry[key] !== card[key])
			fail(`${label}.${key} does not match its catalog entry`);

	for (const key of ['when', 'avoidWhen'])
		for (const [index, text] of boundedArray(card[key], 1, 6, `${label}.${key}`).entries())
			boundedString(text, 1, 240, `${label}.${key}[${index}]`);

	uniqueStrings(card.effectiveAgainst, 1, 8, `${label}.effectiveAgainst`, TagPattern);
	uniqueStrings(card.hardCounteredBy, 1, 8, `${label}.hardCounteredBy`, TagPattern);
	for (const requirement of uniqueStrings(card.requirements, 0, 4, `${label}.requirements`, TagPattern))
		if (!AllowedRequirements.has(requirement))
			fail(`${label}.requirements contains unknown requirement ${requirement}`);

	const claims = new Map();
	for (const [index, claim] of boundedArray(card.claims, 1, 64, `${label}.claims`).entries())
	{
		const claimLabel = `${label}.claims[${index}]`;
		exactKeys(claim, ['epistemic', 'id', 'sourceRefs', 'statement'], claimLabel);
		if (!ClaimIdPattern.test(claim?.id ?? ''))
			fail(`${claimLabel}.id is invalid`);
		else if (claims.has(claim.id))
			fail(`${claimLabel}.id duplicates ${claim.id}`);
		else
			claims.set(claim.id, claim);
		if (!AllowedEpistemics.has(claim?.epistemic))
			fail(`${claimLabel}.epistemic is invalid`);
		boundedString(claim?.statement, 1, 240, `${claimLabel}.statement`);
		const refs = uniqueStrings(claim?.sourceRefs, 1, 6, `${claimLabel}.sourceRefs`);
		if (claim?.epistemic === 'ruleFact' && !refs.some(ref => /^(actor|source|weapon):/.test(ref)))
			fail(`${claimLabel} ruleFact must cite an actor, weapon, or source`);
		if (claim?.epistemic === 'derivedComparison' && refs.length < 2)
			fail(`${claimLabel} derivedComparison must cite at least two inputs`);
		if (claim?.epistemic === 'curatedHeuristic' && !refs.some(ref => ref.startsWith('corpus:')))
			fail(`${claimLabel} curatedHeuristic must cite the curated corpus`);

		for (const ref of refs)
		{
			const separator = ref.indexOf(':');
			if (separator <= 0 || separator === ref.length - 1)
			{
				fail(`${claimLabel} has malformed source ref ${JSON.stringify(ref)}`);
				continue;
			}

			const kind = ref.slice(0, separator);
			const id = ref.slice(separator + 1);
			if (!['actor', 'corpus', 'counter', 'source', 'weapon'].includes(kind))
				fail(`${claimLabel} has unknown source ref kind ${kind}`);
			else if (kind === 'actor' && !graphIds.actors.has(id))
				fail(`${claimLabel} cites missing rules actor ${id}`);
			else if (kind === 'weapon' && !graphIds.weapons.has(id))
				fail(`${claimLabel} cites missing rules weapon ${id}`);
		}

		const actorRefs = refs.filter(ref => ref.startsWith('actor:')).map(ref => ref.slice(6));
		const weaponRefs = refs.filter(ref => ref.startsWith('weapon:')).map(ref => ref.slice(7));
		if (claim?.epistemic === 'ruleFact' && actorRefs.length && weaponRefs.length)
			for (const weapon of weaponRefs)
				if (!actorRefs.some(actor => graphIds.weaponActors.get(weapon)?.has(actor)))
					fail(`${claimLabel} cites weapon ${weapon} without one of its owning actors`);
	}

	const usedClaims = new Set();
	function validateClaimRefs(refs, refLabel)
	{
		for (const ref of uniqueStrings(refs, 1, 12, refLabel, ClaimIdPattern))
		{
			usedClaims.add(ref);
			if (!claims.has(ref))
				fail(`${refLabel} cites missing claim ${ref}`);
		}
	}

	for (const [index, phase] of boundedArray(card.phases, 1, 8, `${label}.phases`).entries())
	{
		const phaseLabel = `${label}.phases[${index}]`;
		exactKeys(phase, ['actionTypes', 'claimRefs', 'name', 'objective'], phaseLabel);
		boundedString(phase?.name, 1, 32, `${phaseLabel}.name`);
		boundedString(phase?.objective, 1, 240, `${phaseLabel}.objective`);
		for (const actionType of uniqueStrings(phase?.actionTypes, 1, 8, `${phaseLabel}.actionTypes`, TagPattern))
			if (!AllowedActionTypes.has(actionType))
				fail(`${phaseLabel}.actionTypes contains unknown action ${actionType}`);
		validateClaimRefs(phase?.claimRefs, `${phaseLabel}.claimRefs`);
	}

	for (const [index, transition] of boundedArray(card.abortTransitions, 1, 8, `${label}.abortTransitions`).entries())
	{
		const transitionLabel = `${label}.abortTransitions[${index}]`;
		exactKeys(transition, ['claimRefs', 'transitionTo', 'when'], transitionLabel);
		boundedString(transition?.when, 1, 240, `${transitionLabel}.when`);
		if (!catalogIds.has(transition?.transitionTo))
			fail(`${transitionLabel}.transitionTo cites missing strategy ${transition?.transitionTo}`);
		if (transition?.transitionTo === card.id)
			fail(`${transitionLabel}.transitionTo may not cite itself`);
		validateClaimRefs(transition?.claimRefs, `${transitionLabel}.claimRefs`);
	}

	for (const claimId of claims.keys())
		if (!usedClaims.has(claimId))
			fail(`${label}.claims contains unused claim ${claimId}`);

	if (exactKeys(card.retrieval, ['actorCodes', 'counterRows', 'situationIds'], `${label}.retrieval`))
	{
		uniqueStrings(card.retrieval.actorCodes, 1, 16, `${label}.retrieval.actorCodes`, TagPattern);
		uniqueStrings(card.retrieval.counterRows, 1, 12, `${label}.retrieval.counterRows`, TagPattern);
		uniqueStrings(card.retrieval.situationIds, 1, 12, `${label}.retrieval.situationIds`, TagPattern);
	}
}

const catalog = readJson(CatalogPath, 'catalog');
if (catalog)
{
	exactKeys(catalog, [
		'cards', 'catalogHash', 'catalogVersion', 'rulesArtifactHash', 'rulesGraphFile', 'rulesGraphHash', 'rulesHash', 'schemaVersion'
	], 'catalog');
	if (catalog.schemaVersion !== 1)
		fail('catalog.schemaVersion must be 1');
	if (!Number.isInteger(catalog.catalogVersion) || catalog.catalogVersion < 1)
		fail('catalog.catalogVersion must be a positive integer');
	if (catalog.rulesGraphFile !== '../ra-arsenal.json')
		fail('catalog.rulesGraphFile must be ../ra-arsenal.json');
	if (!HashPattern.test(catalog.rulesGraphHash ?? ''))
		fail('catalog.rulesGraphHash must be a lowercase SHA-256 hash');
	if (!HashPattern.test(catalog.rulesHash ?? ''))
		fail('catalog.rulesHash must be a lowercase SHA-256 hash');
	if (!HashPattern.test(catalog.rulesArtifactHash ?? ''))
		fail('catalog.rulesArtifactHash must be a lowercase SHA-256 hash');
	if (!HashPattern.test(catalog.catalogHash ?? ''))
		fail('catalog.catalogHash must be a lowercase SHA-256 hash');
	else
	{
		const hashableCatalog = { ...catalog };
		delete hashableCatalog.catalogHash;
		const expectedHash = sha256(canonicalJson(hashableCatalog));
		if (catalog.catalogHash !== expectedHash)
			fail(`catalog.catalogHash mismatch: expected ${expectedHash}`);
	}

	const rulesGraphPath = path.resolve(StrategyDirectory, catalog.rulesGraphFile ?? '');
	const expectedRulesGraphPath = path.resolve(StrategyDirectory, '../ra-arsenal.json');
	if (rulesGraphPath !== expectedRulesGraphPath || !fs.existsSync(rulesGraphPath))
		fail('catalog rules graph is missing or escapes the knowledge directory');
	const rulesGraphBytes = fs.existsSync(rulesGraphPath) ? fs.readFileSync(rulesGraphPath) : Buffer.alloc(0);
	if (rulesGraphBytes.length && sha256(rulesGraphBytes) !== catalog.rulesGraphHash)
		fail(`catalog.rulesGraphHash mismatch: expected ${sha256(rulesGraphBytes)}`);
	const rulesGraph = rulesGraphBytes.length ? readJson(rulesGraphPath, 'rules graph') : null;
	if (rulesGraph?.rulesHash !== catalog.rulesHash)
		fail(`catalog.rulesHash mismatch: expected ${rulesGraph?.rulesHash ?? 'missing'}`);
	if (rulesGraph?.artifactHash !== catalog.rulesArtifactHash)
		fail(`catalog.rulesArtifactHash mismatch: expected ${rulesGraph?.artifactHash ?? 'missing'}`);
	const graphIds = graphIdentifiers(rulesGraph);

	const entries = boundedArray(catalog.cards, 4, 12, 'catalog.cards');
	const ids = entries.map(entry => entry?.id);
	const sortedIds = [...ids].sort((left, right) => left < right ? -1 : left > right ? 1 : 0);
	if (ids.join('\0') !== sortedIds.join('\0'))
		fail('catalog.cards must be sorted by ordinal strategy id');
	if (new Set(ids).size !== ids.length)
		fail('catalog.cards contains duplicate strategy ids');
	const catalogIds = new Set(ids);
	const menuLines = [];
	const generatedEntries = [];

	for (const [index, entry] of entries.entries())
	{
		const label = `catalog.cards[${index}]`;
		exactKeys(entry, ['archetype', 'cardHash', 'faction', 'file', 'id', 'openingSummary', 'title', 'version'], label);
		if (!IdPattern.test(entry?.id ?? ''))
			fail(`${label}.id is invalid`);
		if (!Number.isInteger(entry?.version) || entry.version < 1)
			fail(`${label}.version must be a positive integer`);
		if (!HashPattern.test(entry?.cardHash ?? ''))
			fail(`${label}.cardHash must be a lowercase SHA-256 hash`);
		if (typeof entry?.file !== 'string' || entry.file !== `cards/${entry.id}.strategy.json`)
			fail(`${label}.file must be cards/${entry.id}.strategy.json`);

		const cardPath = path.resolve(StrategyDirectory, entry.file ?? '');
		const cardDirectory = path.resolve(StrategyDirectory, 'cards');
		if (!cardPath.startsWith(`${cardDirectory}${path.sep}`) || !fs.existsSync(cardPath))
		{
			fail(`${label}.file is missing or escapes the cards directory`);
			continue;
		}

		const cardBytes = fs.readFileSync(cardPath);
		if (cardBytes.length > 12 * 1024)
			fail(`${label}.file exceeds the 12 KiB source bound`);
		const card = readJson(cardPath, `card ${entry.id}`);
		if (!card)
			continue;
		// cardHash is an exact-file integrity pin shared with the runtime loader.
		// The catalogHash below remains the canonical semantic-content hash.
		const cardHash = sha256(cardBytes);
		if (cardHash !== entry.cardHash)
			fail(`${label}.cardHash mismatch: expected ${cardHash}`);
		validateCard(card, entry, catalogIds, graphIds);
		generatedEntries.push({
			id: entry.id,
			version: entry.version,
			faction: entry.faction,
			requirements: Array.isArray(card.requirements) ? card.requirements : []
		});

		const menuLine = `${entry.id}@${entry.version} | ${entry.faction} | ${entry.archetype} | opening ${entry.openingSummary} | pick ${card.when?.[0] ?? ''} | counters ${(card.hardCounteredBy ?? []).join(',')}`;
		if (menuLine.length > 360)
			fail(`${label} menu line exceeds 360 characters`);
		menuLines.push(menuLine);
	}

	const menu = menuLines.join('\n');
	if (Buffer.byteLength(menu, 'utf8') > 4096)
		fail('strategy menu exceeds the 4 KiB prompt bound');

	if (errors.length === 0)
	{
		if (!fs.existsSync(ManualPath))
			fail('situation manual is missing');
		const catalogFileHash = sha256(fs.readFileSync(CatalogPath));
		const manualFileHash = fs.existsSync(ManualPath) ? sha256(fs.readFileSync(ManualPath)) : '';
		const generated = renderGeneratedCatalog(catalog, catalogFileHash, manualFileHash, generatedEntries);
		if (WriteGenerated)
			fs.writeFileSync(GeneratedCatalogPath, generated);

		if (!fs.existsSync(GeneratedCatalogPath))
			fail('generated strategy catalog is missing; run with --write-generated');
		else
		{
			const actual = fs.readFileSync(GeneratedCatalogPath, 'utf8');
			if (actual !== generated)
				fail('generated strategy catalog is stale; run with --write-generated');
		}
	}

	if (errors.length === 0)
	{
		if (PrintMenu)
			console.log(menu);
		console.log(`strategy catalog ${catalog.catalogHash} (${entries.length} cards, ${Buffer.byteLength(menu, 'utf8')} menu bytes)`);
	}
}

if (errors.length)
{
	for (const error of errors)
		console.error(`FAIL ${error}`);
	console.error(`STRATEGY CATALOG GATE: FAILED (${errors.length} error${errors.length === 1 ? '' : 's'})`);
	process.exit(1);
}

console.log('STRATEGY CATALOG GATE: PASS');
